"""Write the control-sweep tours: scripts/nav_paths/controls_*.txt, from the Options tours.

Purpose: each controls_* tour is a tour_options_* tour with a `!CONTROLS` step after every settings page (Options, Audio, Advanced, Realism), which
clicks every checkbox and spinner there and checks which of them changed on screen. They are not in the navigation suite (they change settings in
the running game, and a mode's copy of a page shares its profile keys with the others): `gtr2-control-check.py` runs each in its own game launch
and then compares the profile the game wrote on exit with what the clicks should have saved.
Usage:   scripts\\.venv\\Scripts\\python.exe -I scripts\\gen-controls-tours.py [--dry-run]
Example: scripts\\.venv\\Scripts\\python.exe -I scripts\\gen-controls-tours.py --dry-run
"""
import argparse
import sys
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPTS / "gtr2_ui"))
import coords  # noqa: E402

PATHS = SCRIPTS / "nav_paths"
MODES = {"main": "tour_options_main", "school": "tour_options_school", "practice": "tour_options_practice", "24h": "tour_options_24h"}


def build(source):
    out = []
    for line in source.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        out.append(line)
        cols = [c.strip() for c in line.split("|")]
        dest = cols[2] if len(cols) > 2 else None
        if dest and coords.control_expectation(dest) is not None:
            out.append("%s | !CONTROLS | %s" % (dest, dest))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    for mode, tour in MODES.items():
        steps = build(PATHS / (tour + ".txt"))
        header = (
            "# Control sweep (%s): every checkbox and spinner of the Options, Audio, Advanced and Realism pages clicked once\n"
            "# Generated by scripts/gen-controls-tours.py from %s.txt. CHANGES SETTINGS in the running game (the profile is written on exit):\n"
            "# run only through scripts/gtr2-control-check.py, which launches the game for this tour alone, compares the profile and reverts it.\n"
            "# Needs:  gtr2-nav.py path --setting-step FILE\n"
            "# Format: PAGE | LABEL | EXPECTED PAGE   ('!CONTROLS' clicks every control of the page shown)\n" % (mode, tour))
        text = header + "\n".join(steps) + "\n"
        if a.dry_run:
            print("%s: %d steps, %d !CONTROLS" % (mode, len(steps), sum("!CONTROLS" in s for s in steps)))
            continue
        (PATHS / ("controls_%s.txt" % mode)).write_text(text, encoding="utf-8", newline="\n")
        print("wrote controls_%s.txt (%d steps)" % (mode, len(steps)))


if __name__ == "__main__":
    main()
