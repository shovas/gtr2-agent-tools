r"""Release notes from git history: commits grouped by day, each day ordered Highlights, Improvements, Fixes, Documentation.

Categories come from the first word of the commit subject: `highlight:`, `improve:`, `fix:`, `docs:`, or `chore:` / `changelog:` / `skip:` (left
out). A commit can be re-categorised or reworded without touching history in `scripts/changelog_overrides.json`: {hash prefix: [[category,
text], ...]} (one commit may give several lines, e.g. a highlight and a fix). Untagged commits without an override are listed under
"Unsorted" and `--check` fails until they are tagged. Highlights are what users of the tools care about (new abilities, faster, easier);
improvements are mostly for agents and tests; fixes are corrected behaviour; documentation is notes only.
Standard library only; only reads git (writes CHANGES.md with --write).

    python -I scripts\changelog.py                 print the notes
    python -I scripts\changelog.py --write         regenerate CHANGES.md in the repository root
    python -I scripts\changelog.py --check         list commits that still need a tag (exit 1 if any)
    python -I scripts\changelog.py --since 2026-11-14 [--until 2026-11-15]
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OVERRIDES = Path(__file__).resolve().parent / "changelog_overrides.json"
ORDER = [("highlight", "Highlights"), ("improve", "Improvements"), ("fix", "Fixes"), ("docs", "Documentation"), ("unsorted", "Unsorted (tag these)")]
ALIASES = {"highlights": "highlight", "feature": "highlight", "feat": "highlight", "improvement": "improve", "improvements": "improve",
           "fixes": "fix", "doc": "docs", "documentation": "docs"}
SKIP = {"chore", "changelog", "skip"}


def commits():
    out = subprocess.run(["git", "-C", str(ROOT), "log", "--format=%H%x1f%h%x1f%ad%x1f%s", "--date=short"], capture_output=True, text=True, check=True).stdout
    rows = []
    for line in out.splitlines():
        full, short, day, subject = line.split("\x1f", 3)
        rows.append((full, short, day, subject))
    return rows


def entries(rows, overrides):
    """[(day, category, text, hash)] in git order; skipped commits left out."""
    out = []
    for full, short, day, subject in rows:
        given = next((v for k, v in overrides.items() if full.startswith(k)), None)
        if given is not None:
            for cat, text in given:
                if cat not in SKIP:
                    out.append((day, ALIASES.get(cat, cat), text, short))
            continue
        m = re.match(r"(\w+)(?:\([^)]*\))?:\s*(.+)", subject)
        if m and (m.group(1).lower() in SKIP):
            continue
        if m and ALIASES.get(m.group(1).lower(), m.group(1).lower()) in {c for c, _ in ORDER}:
            out.append((day, ALIASES.get(m.group(1).lower(), m.group(1).lower()), m.group(2), short))
        else:
            out.append((day, "unsorted", subject, short))
    return out


def render(items, since=None, until=None):
    days = sorted({d for d, *_ in items}, reverse=True)
    lines = ["# Changes", "", "Notes for users of the tools, by day, newest first (generated by `scripts/changelog.py` from the git history and "
             "`scripts/changelog_overrides.json`; do not edit by hand). Each day lists highlights first, then improvements, fixes and documentation. "
             "The detailed, agent-level changes are in the git history (`git log`).", ""]
    for day in days:
        if since and day < since or until and day > until:
            continue
        lines += ["## " + day, ""]
        for cat, title in ORDER:
            rows = [(t, h) for d, c, t, h in items if d == day and c == cat]
            if not rows:
                continue
            lines += ["### " + title, ""] + ["- %s (`%s`)" % (t, h) for t, h in rows] + [""]
    return "\n".join(lines).rstrip("\n") + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--write", action="store_true", help="write CHANGES.md")
    ap.add_argument("--check", action="store_true", help="list commits without a tag or override; exit 1 if any")
    ap.add_argument("--since")
    ap.add_argument("--until")
    a = ap.parse_args()
    overrides = json.loads(OVERRIDES.read_text(encoding="utf-8")) if OVERRIDES.exists() else {}
    items = entries(commits(), overrides)
    if a.check:
        bad = [(d, t, h) for d, c, t, h in items if c == "unsorted"]
        for d, t, h in bad:
            print("%s %s %s" % (d, h, t))
        print("%d commit(s) need a tag" % len(bad))
        return 1 if bad else 0
    text = render(items, a.since, a.until)
    if a.write:
        (ROOT / "CHANGES.md").write_text(text, encoding="utf-8", newline="\n")
        print("wrote CHANGES.md (%d entries)" % len(items))
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
